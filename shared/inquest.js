/* =============================================================================
   inquest.js — правила режима «Следствие».

   Третий режим игры, и он отвечает на самую старую претензию к «Мафии»:
   днём город говорит, но говорить ему не о чем. Вся информация в классической
   игре — это чужие слова и одна проверка шерифа. Отсюда и знакомое всем
   ощущение: победил тот, кто громче.

   В «Следствии» у города появляется то, чего в «Мафии» никогда не было:
   объективные факты, которые нельзя оспорить словами.

   Как это работает.

   1. ПРИМЕТЫ. Каждый за столом получает три приметы — левша, курит, носит
      перстень, хромает, говорит с южным выговором. Свои приметы человек
      знает, чужие — нет. Врать о них можно и нужно.

   2. СПОСОБ. Ночью мафия выбирает не только жертву, но и способ. Способ —
      это честный обмен: грубо и быстро — город получит две улики, зато врач
      не успеет; тихо — одна улика; аккуратно — одна, но такая, которая
      подходит не только убийце. Впервые у мафии есть настоящее решение
      кроме «кого».

   3. УЛИКИ. Утром город получает улики. Улика — всегда правда: она называет
      примету того, кто убивал. Правдивость здесь не любезность, а весь
      смысл: если улики врут, режим превращается в обычный галдёж.

   4. ЭКСПЕРТИЗА. Днём город может сложиться и проверить одного человека по
      одной примете. Большинство живых — и в протоколе появляется факт:
      «У Олега приметы „левша“ нет». Один факт в день, зато железный.

   5. ЗАНАВЕС. Приметы выбывшего становятся общим достоянием. К третьему дню
      у стола на руках доска фактов, и разговор идёт не о том, кто как
      посмотрел, а о том, кто не сходится с уликами.

   Модуль чистый: ни таймеров, ни состояния партии. Всё случайное берётся из
   переданного генератора, поэтому по семени партия повторяется целиком.
   ============================================================================= */
'use strict';

/* -----------------------------------------------------------------------------
   ПРИМЕТЫ

   ru    — как примету видит её владелец («вы левша»);
   clue  — как о ней говорит улика («убийца — левша»);
   Приметы нарочно бытовые и проверяемые на слух: игрок должен уметь как
   соврать про свою, так и поймать чужого на неосторожном слове.
   --------------------------------------------------------------------------- */
const TRAITS = [
  { id: 'left', ru: 'вы левша', clue: 'работал левой рукой' },
  { id: 'smoke', ru: 'вы курите', clue: 'курит — табаком тянуло от рукава' },
  { id: 'ring', ru: 'вы носите перстень', clue: 'носит перстень — остался отпечаток на дереве' },
  { id: 'limp', ru: 'вы прихрамываете', clue: 'припадает на одну ногу — шаг был неровный' },
  { id: 'tall', ru: 'вы высокого роста', clue: 'высокого роста — удар пришёл сверху' },
  { id: 'scent', ru: 'от вас пахнет духами', clue: 'пахнет духами — запах держался до утра' },
  { id: 'glass', ru: 'вы носите очки', clue: 'носит очки — их нашли под столом' },
  { id: 'watch', ru: 'у вас часы на цепочке', clue: 'при часах на цепочке — звено осталось на полу' },
  { id: 'accent', ru: 'вы говорите с южным выговором', clue: 'говорит с южным выговором — жертва успела ответить' },
  { id: 'gloves', ru: 'вы носите перчатки', clue: 'был в перчатках — на ручке нет ни одного отпечатка' },
  { id: 'ink', ru: 'у вас пальцы в чернилах', clue: 'пальцы в чернилах — след остался на скатерти' },
  { id: 'boots', ru: 'вы в тяжёлых сапогах', clue: 'в тяжёлых сапогах — половица под окном промялась' },
  { id: 'mono', ru: 'у вас платок с монограммой', clue: 'у него платок с монограммой — обронил у двери' },
  { id: 'strong', ru: 'вы сильный человек', clue: 'человек сильный — дверь открыли одним движением' },
  { id: 'cough', ru: 'вы кашляете', clue: 'кашляет — соседи слышали кашель в коридоре' },
  { id: 'quiet', ru: 'вы ходите бесшумно', clue: 'ходит бесшумно — никто не слышал шагов' }
];

const TRAIT_BY_ID = {};
TRAITS.forEach(t => { TRAIT_BY_ID[t.id] = t; });

/** Сколько примет у одного человека. Три — предел, который стол держит в голове. */
const TRAITS_PER_PLAYER = 3;

/* -----------------------------------------------------------------------------
   СПОСОБЫ

   clues   — сколько улик оставит эта ночь;
   noHeal  — врач не успевает (жертву не спасти);
   shared  — улика будет выбрана из тех примет убийцы, что есть ещё у кого-то
             живого: улика правдива, но указывает не на одного человека.
   --------------------------------------------------------------------------- */
const METHODS = [
  {
    id: 'rough', ru: 'Грубо и быстро',
    note: 'Врач не успеет никого спасти. Город получит две улики.',
    clues: 2, noHeal: true, shared: false
  },
  {
    id: 'quiet', ru: 'Тихо',
    note: 'Обычная ночь: врач может успеть. Город получит одну улику.',
    clues: 1, noHeal: false, shared: false
  },
  {
    id: 'clean', ru: 'Аккуратно',
    note: 'Одна улика, и она подойдёт не только вам — если за столом есть кто-то с той же приметой.',
    clues: 1, noHeal: false, shared: true
  }
];
const METHOD_BY_ID = {};
METHODS.forEach(m => { METHOD_BY_ID[m.id] = m; });
const DEFAULT_METHOD = 'quiet';

/** Раздать приметы: возвращает { playerId: [traitId, …] }. */
function dealTraits(rng, players) {
  const out = {};
  players.forEach(p => {
    const bag = rng.shuffle(TRAITS.map(t => t.id));
    out[p.id] = bag.slice(0, TRAITS_PER_PLAYER);
  });
  return out;
}

/**
 * Улики этой ночи.
 *
 * Правило одно и оно железное: улика говорит правду о примете убийцы. Всё
 * остальное — только выбор, какую именно примету назвать.
 *
 * @param {object} rng        сеяный генератор партии
 * @param {string} killerId   кто убивал
 * @param {object} traits     карта примет всех игроков
 * @param {string} methodId   способ
 * @param {Array}  alive      живые игроки (для «аккуратно» и для подсчёта)
 * @param {Array}  used       traitId, уже названные в прошлых уликах
 * @returns {Array<{traitId, text, shared}>}
 */
function cluesFor(rng, killerId, traits, methodId, alive, used) {
  const method = METHOD_BY_ID[methodId] || METHOD_BY_ID[DEFAULT_METHOD];
  const mine = (traits[killerId] || []).slice();
  const already = new Set(used || []);

  /* Дважды одну примету не называем: вторая такая улика не добавляет городу
     ничего, а выглядит как насмешка. */
  let pool = mine.filter(t => !already.has(t));
  if (!pool.length) pool = mine;
  if (!pool.length) return [];

  /* «Аккуратно»: ищем примету, которая есть ещё у кого-то живого. Улика
     остаётся правдой, но перестаёт указывать на одного человека. */
  if (method.shared) {
    const shared = pool.filter(t => alive.some(p => p.id !== killerId && (traits[p.id] || []).indexOf(t) >= 0));
    if (shared.length) pool = shared;
  }

  const take = Math.min(method.clues, pool.length);
  const chosen = rng.shuffle(pool).slice(0, take);
  return chosen.map(id => ({
    traitId: id,
    text: TRAIT_BY_ID[id].clue,
    shared: alive.filter(p => (traits[p.id] || []).indexOf(id) >= 0).length > 1
  }));
}

/** Человеческое имя приметы от первого лица. */
function traitRu(id) { return (TRAIT_BY_ID[id] || {}).ru || id; }
/** Как о примете говорит улика. */
function traitClue(id) { return (TRAIT_BY_ID[id] || {}).clue || id; }
/** Короткое название приметы для доски фактов: «левша», «перстень». */
function traitShort(id) {
  const ru = traitRu(id);
  return ru.replace(/^(вы|у вас|от вас)\s+/i, '').replace(/^пахнет/, 'духи');
}

module.exports = {
  TRAITS, TRAIT_BY_ID, TRAITS_PER_PLAYER,
  METHODS, METHOD_BY_ID, DEFAULT_METHOD,
  dealTraits, cluesFor, traitRu, traitClue, traitShort
};
