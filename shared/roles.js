  const DROP_ORDER = ['lawyer', 'journalist', 'lover', 'werewolf', 'maniac'];

  /**
   * Сколько каких новых карт реально попадёт на стол из n человек.
   * Мирных всегда оставляем хотя бы одного: стол, где нет ни одной пустой
   * карты, играется не в мафию, а в перечисление способностей.
   * @param {number} civilians сколько мирных даёт базовый состав
   * @param {object} want сколько новых карт просит пресет
   */
  function fitExtra(civilians, want) {
    const out = Object.assign({}, want || {});
    const total = () => DROP_ORDER.reduce((s, k) => s + (out[k] || 0), 0);
    for (const key of DROP_ORDER) {
      while (total() > 0 && civilians - total() < 1) {
        if (!out[key]) break;
        out[key] -= 1;
        if (!out[key]) delete out[key];
      }
    }
    return out;
  }

