  /* нормализация                                                        */
  /* ------------------------------------------------------------------ */
  function norm(text) {
    return ' ' + String(text == null ? '' : text)
      .toLowerCase()
      .replace(/\u0451/g, '\u0435')            // ё → е
      .replace(/[^0-9a-z\u0430-\u044f?!.,:;()\-\s]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim() + ' ';
  }

  /* Основа имени без окончания: Аня→ан, Гриша→гриш, Виктор→виктор */
  function stemOf(name) {
    var n = String(name || '').toLowerCase().replace(/\u0451/g, '\u0435');
    var s = n.replace(/[\u0430\u044f\u0443\u044e\u043e\u0435\u0438\u044b\u0439]$/, '');
    return s.length < 2 ? n : s;
  }

  /* Найти всех упомянутых в тексте игроков (в любом падеже) */
  function mentions(text, people, selfIdx) {
    var low = norm(text);
    var found = [];
    (people || []).forEach(function (p) {
      if (p.alive === false) return;
      if (selfIdx !== undefined && selfIdx !== null && p.idx === selfIdx) return;
      var re = new RegExp('(^|[\\s,.:;!?()\\-])' + stemOf(p.name) + '[\u0430-\u044f]{0,3}($|[\\s,.:;!?()\\-])');
      var m = low.match(re);
      if (m) found.push({ idx: p.idx, name: p.name, at: low.indexOf(m[0]) });
    });
    found.sort(function (a, b) { return a.at - b.at; });
    return found;
  }

