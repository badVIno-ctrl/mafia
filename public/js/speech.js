      res.kind = 'silence';
      res.repeat = hist.length > 0 && hist[hist.length - 1] === 'silence';
      var ps = PROFILE.silence;
      res.attention = ps.attention;
      res.suspicionDelta = ps.suspicion + (res.repeat ? 0.8 : 0);
      res.tensionDelta = ps.tension + (res.repeat ? 0.4 : 0);
      res.heat = ps.heat;
      return res;
